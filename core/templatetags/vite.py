"""Template tag that loads the Vite assets.

In development it points at the Vite dev server (``npm run dev``). In
production it reads ``static/build/manifest.json`` generated by
``npm run build``.
"""

from __future__ import annotations

import json
from pathlib import Path

from django import template
from django.conf import settings
from django.templatetags.static import static
from django.utils.safestring import mark_safe

register = template.Library()


def _manifest() -> dict:
    candidates = [Path(settings.BASE_DIR) / "static" / "build" / "manifest.json"]
    static_root = getattr(settings, "STATIC_ROOT", None)
    if static_root:
        candidates.append(Path(static_root) / "build" / "manifest.json")
    for path in candidates:
        if path.exists():
            return json.loads(path.read_text(encoding="utf-8"))
    return {}


@register.simple_tag
def vite_assets() -> str:
    """Return the ``<script>`` and ``<link>`` tags for the entrypoint."""
    entry = getattr(settings, "VITE_ENTRY", "frontend/main.ts")

    if settings.DEBUG:
        base = getattr(settings, "VITE_DEV_SERVER", "http://127.0.0.1:5173").rstrip("/")
        return mark_safe(
            f'<script type="module" src="{base}/@vite/client"></script>\n    '
            f'<script type="module" src="{base}/{entry}"></script>'
        )

    manifest = _manifest()
    asset = manifest.get(entry)
    if not asset:
        return mark_safe(
            "<!-- Missing static/build/manifest.json: run 'npm run build'. -->"
        )

    tags = [
        f'<link rel="stylesheet" href="{static("build/" + css)}">'
        for css in asset.get("css", [])
    ]
    tags.append(
        f'<script type="module" src="{static("build/" + asset["file"])}"></script>'
    )
    return mark_safe("\n    ".join(tags))
